const assert=require('node:assert/strict');
const fs=require('node:fs'),ts=require('typescript'),Module=require('node:module'),path=require('node:path');
const file=path.resolve('src/components/Footnote.ts'),m=new Module(file,module);m.filename=file;m.paths=module.paths;
m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {getSchema}=require('@tiptap/core'),StarterKit=require('@tiptap/starter-kit').default;
const {EditorState}=require('@tiptap/pm/state');
const schema=getSchema([StarterKit,m.exports.Footnote]);
const plugin=m.exports.Footnote.config.addProseMirrorPlugins()[0];
const note=(text,n=99)=>schema.nodes.footnote.create({note:text,source:'',number:n});
let state=EditorState.create({schema,plugins:[plugin],doc:schema.nodes.doc.create(null,schema.nodes.paragraph.create(null,[schema.text('A'),note('ilk'),schema.text('B')]))});
const numbers=()=>{let list=[];state.doc.descendants(n=>{if(n.type.name==='footnote')list.push(n.attrs.number)});return list};
state=state.applyTransaction(state.tr.insert(1,note('yeni'))).state;
assert.deepEqual(numbers(),[1,2]);
state=state.applyTransaction(state.tr.delete(1,2)).state;
assert.deepEqual(numbers(),[1]);
state=state.applyTransaction(state.tr.insert(4,note('son'))).state;
assert.deepEqual(numbers(),[1,2]);
assert(state.doc.textContent.includes('AB'));
console.log('PASS: editor insert/delete and sequential renumbering');
